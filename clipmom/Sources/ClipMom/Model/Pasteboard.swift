import AppKit
import Foundation

/// Прочитанное из буфера, ещё не записанное в историю.
struct Captured {
    var kind: ClipKind
    var text: String?
    var rtf: Data?
    var files: [String]?
    var png: Data?
    var pixelWidth: Int?
    var pixelHeight: Int?
    var bytes: Int
    var digest: String
}

enum CaptureResult {
    case captured(Captured)
    case skipped(String)
    case nothing
}

extension NSPasteboard.PasteboardType {
    // Соглашения nspasteboard.org: менеджеры буфера не должны сохранять такие записи.
    static let concealed = Self("org.nspasteboard.ConcealedType")
    static let transient = Self("org.nspasteboard.TransientType")
    static let autoGenerated = Self("org.nspasteboard.AutoGeneratedType")
    static let onePassword = Self("com.agilebits.onepassword")
    /// Кто положил данные в буфер (bundle id) — ClipMom помечает так свои записи.
    static let source = Self("org.nspasteboard.source")
    /// Своя метка: «это ClipMom вернул запись из истории, не записывать повторно».
    static let clipMomRestore = Self("local.clipmom.restored")
}

enum PasteboardReader {
    /// Причина пропуска по одному только списку типов — без чтения содержимого.
    static func skipReason(types: [NSPasteboard.PasteboardType]) -> String? {
        let t = Set(types)
        if t.contains(.concealed) || t.contains(.onePassword) { return "пароль или скрытые данные" }
        if t.contains(.transient) { return "временные данные" }
        if t.contains(.autoGenerated) { return "создано автоматически" }
        if t.contains(.clipMomRestore) { return "своя запись ClipMom" }
        return nil
    }

    /// Читает первую запись буфера. Вызывать только после смены `changeCount`:
    /// на macOS 15.4+/26 чтение общего буфера может показать системный запрос доступа.
    static func read(_ pb: NSPasteboard) -> CaptureResult {
        let types = pb.types ?? []
        if types.isEmpty { return .nothing }
        if let reason = skipReason(types: types) { return .skipped(reason) }

        // Файлы из Finder
        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            let joined = paths.joined(separator: "\n")
            return .captured(Captured(kind: .files, text: joined, files: paths, bytes: joined.utf8.count,
                                      digest: Digest.of(Data(joined.utf8), salt: "files")))
        }

        let imageType: NSPasteboard.PasteboardType? = types.contains(.png) ? .png : (types.contains(.tiff) ? .tiff : nil)
        let hasString = types.contains(.string)
        // Текст с картинкой (Office, Pages кладут ещё и снимок): если строка — не просто ссылка, это текст.
        var preferImage = imageType != nil
        var string: String?
        if hasString {
            string = pb.string(forType: .string)
            if let s = string, !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, LinkDetector.detect(s) == nil {
                preferImage = false
            }
        }

        if preferImage, let it = imageType, let raw = pb.data(forType: it) {
            if raw.count > Limits.maxImageBytes { return .skipped("картинка больше \(Limits.maxImageBytes / 1_000_000) МБ") }
            guard let rep = NSBitmapImageRep(data: raw),
                  let png = it == .png ? raw : rep.representation(using: .png, properties: [:]) else {
                return .skipped("не удалось прочитать картинку")
            }
            if png.count > Limits.maxImageBytes { return .skipped("картинка больше \(Limits.maxImageBytes / 1_000_000) МБ") }
            return .captured(Captured(kind: .image, png: png, pixelWidth: rep.pixelsWide, pixelHeight: rep.pixelsHigh,
                                      bytes: png.count, digest: Digest.of(png, salt: "image")))
        }

        var text = string
        var rtf: Data?
        if types.contains(.rtf), let data = pb.data(forType: .rtf) {
            if data.count <= Limits.maxRTFBytes { rtf = data }
            if text == nil {
                text = NSAttributedString(rtf: data, documentAttributes: nil)?.string
            }
        }
        if text == nil, types.contains(.URL), let u = NSURL(from: pb) as URL? {
            text = u.absoluteString
        }
        guard let s = text, !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return .nothing }
        let data = Data(s.utf8)
        if data.count > Limits.maxTextBytes { return .skipped("текст больше \(Limits.maxTextBytes / 1_000_000) МБ") }
        let kind: ClipKind = LinkDetector.detect(s) != nil ? .link : .text
        return .captured(Captured(kind: kind, text: s, rtf: kind == .text ? rtf : nil, bytes: data.count,
                                  digest: Digest.of(data, salt: "text")))
    }
}

enum PasteboardWriter {
    /// Кладёт запись обратно в буфер, помечая, что это сделал ClipMom. Возвращает новый changeCount.
    @discardableResult
    static func write(_ item: ClipItem, to pb: NSPasteboard, store: HistoryStore) -> Int {
        pb.clearContents()
        switch item.kind {
        case .text, .link:
            let s = item.text ?? ""
            var types: [NSPasteboard.PasteboardType] = [.string]
            if item.rtf != nil { types.append(.rtf) }
            if item.kind == .link { types.append(.URL) }
            pb.addTypes(types, owner: nil)
            pb.setString(s, forType: .string)
            if let rtf = item.rtf { pb.setData(rtf, forType: .rtf) }
            if item.kind == .link, let u = item.url { pb.setString(u.absoluteString, forType: .URL) }
        case .image:
            if let name = item.image, let png = try? Data(contentsOf: store.imageURL(name)) {
                pb.addTypes([.png, .tiff], owner: nil)
                pb.setData(png, forType: .png)
                if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        case .files:
            let urls = (item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pb.writeObjects(urls)
        }
        pb.addTypes([.source, .clipMomRestore], owner: nil)
        pb.setString("local.clipmom", forType: .source)
        pb.setData(Data(), forType: .clipMomRestore)
        return pb.changeCount
    }
}

/// Следит за `changeCount` (не читает содержимое) и отличает свои записи от чужих.
struct ChangeTracker {
    private(set) var lastSeen: Int
    private var ownWrite: Int?

    init(current: Int) { lastSeen = current }

    enum Change { case none, own, external }

    mutating func markOwnWrite(_ changeCount: Int) {
        ownWrite = changeCount
        lastSeen = changeCount
    }

    mutating func check(_ changeCount: Int) -> Change {
        guard changeCount != lastSeen else { return .none }
        lastSeen = changeCount
        if changeCount == ownWrite { return .own }
        return .external
    }
}

/// Доступ к общему буферу (macOS 15.4+, на macOS 26 — «Вставка из других приложений»).
enum PasteAccess: Equatable {
    case unsupported  // macOS до 15.4: запросов нет
    case notAsked     // .default — запрос ещё ни разу не показывался
    case ask          // каждый раз спрашивать
    case allowed
    case denied

    static func of(_ pb: NSPasteboard) -> PasteAccess {
        guard #available(macOS 15.4, *) else { return .unsupported }
        switch pb.accessBehavior {
        case .default: return .notAsked
        case .ask: return .ask
        case .alwaysAllow: return .allowed
        case .alwaysDeny: return .denied
        @unknown default: return .ask
        }
    }

    /// Можно ли читать буфер автоматически, не засыпая пользователя запросами.
    var canAutoRead: Bool { self == .unsupported || self == .notAsked || self == .allowed }

    var title: String {
        switch self {
        case .unsupported: "Доступ к буферу не ограничен"
        case .notAsked: "macOS может спросить про доступ к буферу"
        case .ask: "macOS спрашивает при каждом копировании"
        case .allowed: "Доступ к буферу разрешён"
        case .denied: "Доступ к буферу запрещён"
        }
    }

    /// Пункт «Вставка из других приложений» в «Конфиденциальность и безопасность».
    static func openSettings() {
        let urls = ["x-apple.systempreferences:com.apple.settings.PrivacySecurity.extension?Privacy_Pasteboard",
                    "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard",
                    "x-apple.systempreferences:com.apple.settings.PrivacySecurity.extension"]
        for s in urls {
            if let u = URL(string: s), NSWorkspace.shared.open(u) { return }
        }
    }
}
